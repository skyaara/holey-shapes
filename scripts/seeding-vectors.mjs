// Usage: node scripts/seeding-vectors.mjs
// Writes packages/seeding-vectors.tsv: the JavaScript package's answers for
// seeded identities, every hue step and extrusion colors. The Swift and Kotlin
// checks read the same file, so all three platforms must agree exactly.
import { writeFile } from 'node:fs/promises';
import { seededHoleyOptions } from '../packages/js/index.js';
import { extrusionColor, hueColor } from '../packages/js/color.js';

const names = ['', 'relay-agent', 'ada', 'Ada', 'ada lovelace', 'héllo 👋', '名前', 'bot:planner', 'x'.repeat(64)];
let state = 1;
const random = () => (state = (state * 48271) % 2147483647) / 2147483647;
const letters = 'abcdefghijklmnopqrstuvwxyz0123456789_.-';
for (let i = 0; i < 1000; i++) {
  const length = 1 + Math.floor(random() * 15);
  names.push(Array.from({ length }, () => letters[Math.floor(random() * letters.length)]).join(''));
}

const faces = ['#000000', '#FFFFFF', '#808080', '#25262A', '#6337FF', '#FF6A00', '#FFD000', '#9BED00', '#00DBFF', '#FF0878'];
for (let i = 0; faces.length < 300; i++) {
  faces.push(`#${Array.from({ length: 3 }, () => Math.floor(random() * 256).toString(16).padStart(2, '0')).join('').toUpperCase()}`);
}

const lines = ['# kind\tinput\tvalues… (generated by scripts/seeding-vectors.mjs; do not edit)'];
for (const name of names) {
  const o = seededHoleyOptions(name);
  lines.push(['seed', name, o.shape, o.holes, o.seed, o.turn, o.mirror ? 1 : 0, o.color, o.shadowColor].join('\t'));
}
for (let tenths = 0; tenths < 3600; tenths++) lines.push(['hue', tenths, hueColor(tenths / 10)].join('\t'));
for (const face of faces) lines.push(['extrusion', face, extrusionColor(face)].join('\t'));
await writeFile(new URL('../packages/seeding-vectors.tsv', import.meta.url), `${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length - 1} vectors to packages/seeding-vectors.tsv`);
