// Usage: node scripts/rust-fixtures.mjs
// Writes packages/rust/tests/fixtures: the JavaScript package's layouts for
// every shape, hole count and a spread of seeds, and whole documents for a
// few option sets, so the Rust package is checked against it byte for byte.
// The Rust tests also read packages/seeding-vectors.tsv.
import { writeFile } from 'node:fs/promises';
import { createHoleySvg, seededHoleyOptions, shapes } from '../packages/js/index.js';

const out = new URL('../packages/rust/tests/fixtures/', import.meta.url);

// Every shape, hole count and a spread of seeds, as `cx,cy,rx,ry,rotate`.
const seeds = [0, 1, 2, -7, 42, 922032, -1000000];
const layouts = ['# shape\tholes\tseed\tlayout (generated by scripts/rust-fixtures.mjs; do not edit)'];
for (const shape of shapes) {
  for (let holes = 0; holes <= 8; holes++) {
    for (const seed of seeds) {
      const svg = createHoleySvg({ shape: shape.key, holes, seed, animated: false });
      const found = [...svg.matchAll(/<ellipse cx="([^"]+)" cy="([^"]+)" rx="([^"]+)" ry="([^"]+)"(?: transform="rotate\(([^ ]+) [^)]+\)")?\/>/g)];
      const layout = found.map(([, cx, cy, rx, ry, rotate]) => [cx, cy, rx, ry, rotate ?? 0].join(',')).join(';');
      layouts.push([shape.key, holes, seed, layout].join('\t'));
    }
  }
}
await writeFile(new URL('layouts.tsv', out), `${layouts.join('\n')}\n`);

// Whole documents, so markup, filters, scoping and doodles match byte for byte.
const cases = [
  ['seeded-relay-agent', { ...seededHoleyOptions('relay-agent') }],
  ['seeded-ada-static', { ...seededHoleyOptions('ada', false), idPrefix: 'chat:ada' }],
  ['seeded-empty-doodle', { ...seededHoleyOptions(''), doodle: true }],
  ['seeded-planner-doodle-static', { ...seededHoleyOptions('bot:planner', false), doodle: true, idPrefix: 'é_1' }],
  ['defaults', {}],
  ['flower-doodle-ink', { shape: 'flower-star', color: '#F786A8', doodle: true, idPrefix: 'my-doodle' }],
  ['bowtie-custom', { shape: 'bowtie', holes: 8, seed: -3, turn: -450, mirror: true, color: '#123abc', shadowColor: '#000000', shadowX: -30, shadowY: 4.25, shadowSteps: 5, duration: 2500 }],
  ['long-bar-none', { shape: 'long-bar', holes: 0, animated: false, idPrefix: '' }]
];
const svgs = cases.map(([name, options]) => `${name}\t${createHoleySvg(options)}`);
await writeFile(new URL('svgs.tsv', out), `${svgs.join('\n')}\n`);
console.log(`Wrote ${layouts.length - 1} layouts and ${svgs.length} documents to packages/rust/tests/fixtures`);
