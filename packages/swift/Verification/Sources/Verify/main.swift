import Foundation
import HoleyShapes

for value in [Double.nan, Double.infinity, -Double.infinity] {
  let config = HoleyShapeConfiguration(duration: value, shadowX: value, shadowY: value)
  precondition(config.duration == 0.9 && config.shadowX == 18 && config.shadowY == 21)
}
let bounded = HoleyShapeConfiguration(duration: -5, shadowX: 500, shadowY: -500)
precondition(bounded.duration == 0.1 && bounded.shadowX == 80 && bounded.shadowY == -80)

// Shared with the JavaScript and Kotlin tests so every platform hashes IDs the same way.
precondition(HoleyShapeConfiguration.identityHash("") == "cbf29ce484222325")
precondition(HoleyShapeConfiguration.identityHash("relay-agent") == "0cc0c8aa3dbd893e")
precondition(HoleyShapeConfiguration.identityHash("héllo 👋") == "7f88f6cbd1e4ef7d")
let relay = HoleyShapeConfiguration.seeded("relay-agent")
precondition(relay.shape == .triangle && relay.seed == 168_748)

var layouts: [[String: Any]] = []
for shape in HoleyShape.allCases {
  for count in 0...8 {
    for seed in [0, 1, 7, 42, -19] {
      let holes = HoleyShapes.layout(shape: shape, count: count, seed: seed)
      precondition(holes.count == count)
      precondition(holes == HoleyShapes.layout(shape: shape, count: count, seed: seed))
      let areas = holes.map { $0.rx * $0.ry }
      if let smallest = areas.min(), let largest = areas.max() {
        precondition(smallest > 0 && largest.isFinite && largest / smallest < 1.001)
        if shape == .disc && count == 1 { precondition(smallest > 10000) }
      }
      layouts.append(["shape": shape.rawValue, "count": count, "seed": seed,
        "holes": holes.map { ["cx": $0.cx, "cy": $0.cy, "rx": $0.rx, "ry": $0.ry, "rotation": $0.rotation] }])
    }
  }
}
precondition(HoleyShapes.layout(count: Int.min, seed: Int.min).isEmpty)
precondition(HoleyShapes.layout(count: Int.max, seed: Int.max).count == 8)
let data = try JSONSerialization.data(withJSONObject: layouts, options: [.sortedKeys])
try data.write(to: URL(fileURLWithPath: CommandLine.arguments[1]))
print("Swift process passed: \(layouts.count) layouts")

// Optional visual samples use catalog outlines, with every hole generated by Swift.
if CommandLine.arguments.count == 4 {
  let catalogData = try Data(contentsOf: URL(fileURLWithPath: CommandLine.arguments[2]))
  let catalog = try JSONSerialization.jsonObject(with: catalogData) as! [[String: Any]]
  let output = URL(fileURLWithPath: CommandLine.arguments[3], isDirectory: true)
  try FileManager.default.createDirectory(at: output, withIntermediateDirectories: true)
  for shape in HoleyShape.allCases {
    let entry = catalog.first { $0["key"] as? String == shape.rawValue }!
    let path = entry["path"] as! String
    let holes = HoleyShapes.layout(shape: shape, count: shape.defaultHoleCount, seed: 7)
    let ellipses = holes.map {
      "<ellipse cx=\"\($0.cx)\" cy=\"\($0.cy)\" rx=\"\($0.rx)\" ry=\"\($0.ry)\" transform=\"rotate(\($0.rotation) \($0.cx) \($0.cy))\"/>"
    }.joined()
    let body = "<path d=\"\(path)\" mask=\"url(#holes)\"/>"
    let depth = stride(from: 12, through: 1, by: -1).map { step in
      "<g fill=\"#252038\" transform=\"translate(\(Double(step) * 1.5) \(Double(step) * 1.75))\">\(body)</g>"
    }.joined()
    let svg = "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 420 420\"><title>Swift: \(shape.name)</title><defs><mask id=\"holes\"><rect width=\"420\" height=\"420\" fill=\"white\"/><g fill=\"black\">\(ellipses)</g></mask></defs>\(depth)<g fill=\"\(shape.color.hex)\">\(body)</g></svg>"
    try svg.write(to: output.appendingPathComponent("\(shape.rawValue).svg"), atomically: true, encoding: .utf8)
  }
  print("Swift wrote 14 SVG samples to \(output.path)")
}
